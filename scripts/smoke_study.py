#!/usr/bin/env python3
"""Run the study protocol end to end on the deterministic synthetic dataset.

This is a *smoke test with numbers*, not a benchmark: the data is generated by our own
function, on one split, with one seed. Its purpose is to prove the pipeline runs and to give
a reviewer a reproducible baseline to compare future changes against.

    ./.venv/bin/python scripts/smoke_study.py

See docs/benchmark.md for the recorded output and how to interpret (and not interpret) it.
"""

from __future__ import annotations

import platform
import time
from datetime import date

from forecastops_forecasting import StudyConfig, generate_demo_demand, run_forecast_study


def main() -> int:
    frame = generate_demo_demand(days=365, seed=20240517, end_date=date(2025, 12, 31))
    series = frame.groupby(["store", "item"]).size().shape[0]

    config = StudyConfig(horizon_days=14, holdout_days=14, validation_folds=2, seed=42)

    print("ForecastOps synthetic smoke — NOT a benchmark, NOT real retail demand")
    print(f"python {platform.python_version()} · {series} series · {len(frame):,} rows · "
          f"horizon {config.horizon_days}d · holdout {config.holdout_days}d · "
          f"folds {config.validation_folds} · seed {config.seed}")

    started = time.perf_counter()
    result = run_forecast_study(frame, config)
    elapsed = time.perf_counter() - started

    print(f"\nselected model: {result['selected_model']}  ({elapsed:.1f}s)")
    print("\n| model | MAE | RMSE | WAPE | MASE | bias | vs baseline WAPE |")
    print("| --- | --- | --- | --- | --- | --- | --- |")
    for row in result["comparison"]["rows"]:
        metrics = next(run["metrics"]["aggregate"] for run in result["runs"] if run["model_key"] == row["model_key"])

        def fmt(value: float | None) -> str:
            return "n/a" if value is None else f"{value:.3f}"

        print(
            f"| {row['label']} | {fmt(metrics['mae'])} | {fmt(metrics['rmse'])} | "
            f"{fmt(metrics['wape'])} | {fmt(metrics['mase'])} | {fmt(metrics['bias'])} | "
            f"{fmt(row['relative_wape_vs_baseline'])} |"
        )

    # Selection and reporting are separate on purpose: say so when they disagree.
    holdout_best = min(
        result["runs"],
        key=lambda run: run["metrics"]["aggregate"]["wape"]
        if run["metrics"]["aggregate"]["wape"] is not None
        else 2.0,
    )
    print(
        f"\nselection chose {result['selected_model']} on rolling-origin WAPE; "
        f"lowest holdout WAPE was {holdout_best['model_key']} "
        f"({holdout_best['metrics']['aggregate']['wape']:.3f}). "
        "The holdout is reported, never used to select."
    )

    selected_rate = next(run for run in result["runs"] if run["model_key"] == result["selected_model"])
    per_series = [row for row in selected_rate["metrics"]["per_series"] if row["wape"] is not None]
    worst = sorted(per_series, key=lambda row: row["wape"], reverse=True)[:3]
    print(f"\nweakest series by holdout WAPE ({result['selected_model']}):")
    for row in worst:
        print(f"- {row['series_key']}: {row['wape']:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
